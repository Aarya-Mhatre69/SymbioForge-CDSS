"""Generate docs/PROJECT_REPORT.md from artifacts + reports so numbers never drift. Run after evaluate.py."""
import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

R = Path(__file__).parent
ev = json.loads((R / "reports/evaluation.json").read_text())
meta = json.loads((R / "artifacts/meta.json").read_text())
comp = pd.read_csv(R / "reports/Task6_model_comparison.csv")
try:
    t = subprocess.run([sys.executable, "-m", "pytest", "-q"], cwd=R, capture_output=True, text=True).stdout.strip().splitlines()[-1]
except Exception:
    t = "pytest not run"

f = lambda x, n=3: "n/a" if x is None else f"{x:.{n}f}"
md = lambda df: df.to_markdown(index=False) if hasattr(df, "to_markdown") else df.to_string(index=False)


def table(rows, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(out)


mods = [{"model": k, **{m: f(v[m]) for m in ("accuracy", "precision", "recall", "roc_auc", "brier")}} for k, v in ev["models"].items()]
cmp_rows = [{"model": r.model, "CV AUC": f"{r.cv_auc_mean:.3f}±{r.cv_auc_std:.3f}", "test acc": f(r.test_accuracy), "test F1": f(r.test_f1),
             "test AUC": f(r.test_roc_auc)} for r in comp.itertuples()]
abl = [{"subset": k, "n": v["n"], "accuracy": f(v["accuracy"]), "AUC": f(v["roc_auc"])} for k, v in ev["ablation_imputation"].items()]
fair = [{"group": f"{k}: {g}", "n": v["n"], "AUC": f(v["roc_auc"]), "recall": f(v["recall"]), "precision": f(v["precision"]), "prevalence": f(v["prevalence"], 2)}
        for k, gs in ev["fairness"].items() for g, v in gs.items()]
bands = [{"confidence": b["band"], "n": b["n"], "accuracy": f(b["accuracy"])} for b in ev["trust_bands_test"]]
ru, cf, md_, cal, lat, rob = ev["rules"], ev["conformal"], ev["model_disagreement"], ev["calibration"], ev["latency_ms_full_pipeline"], ev["robustness"]
shap = [{"feature": k, "mean |SHAP|": f(v)} for k, v in ev["global_shap"].items()]

doc = f"""# SymbioForge CDSS: Project Report

Decision support only, not a diagnosis. Academic prototype; generated by `build_docs.py` from `reports/evaluation.json`.

## 1. Summary
An integrated clinical decision support prototype for cardiovascular disease. It takes 10 required and 3 optional patient attributes and returns a risk estimate, an
agreement check against the explicit Task 2 rule base, a per-patient explanation, a confidence indicator with a conformal prediction set, a counterfactual hint, a next-test
recommendation, and a printable report. Everything runs locally with a zero-cost stack (Python, XGBoost, numpy, Streamlit).

Data: `data/heart_dataset.csv`, {meta['dataset']['rows_raw']} rows, 4 sites, same schema as the UCI Heart Disease data. After cleaning (context.md section 5) {meta['dataset']['rows_clean']} rows,
disease prevalence {meta['dataset']['prevalence']:.1%}. Split stratified 70/15/15 (train {meta['split_sizes']['train']} / val {meta['split_sizes']['val']} / test {meta['split_sizes']['test']}), seed 42.

Data quality, distributions, missingness by site and correlations: `reports/EDA_report.md`.

## 2. Design (SDD summary)
The system orchestrates the Task 1-8 workflows (intake, feature, risk model, second-opinion model, clinical rules, trust, explainer, what-if, test planner) into a synthesizer that produces the patient overview. The live trace is shown in the app's How it works view.

Pipeline: `PatientInput` (pydantic) -> mode-impute optional fields and record which -> `engineer()` (12 features, exact order) -> XGBoost + DNN -> rules (on observed values only) ->
SHAP -> confidence -> counterfactual -> advisor -> summary/report. Full diagram: ARCHITECTURE.md. Decisions that differ from the first draft of the docs:

| Decision | Why | Trade-off |
|---|---|---|
| XGBoost is the verdict; DNN is a second opinion (replaces "mean ensemble") | The mean ensemble was within noise of XGBoost on test (AUC {f(ev['models']['mean_ensemble']['roc_auc'])} vs {f(ev['models']['xgb']['roc_auc'])}); SHAP explains XGBoost, so verdict and explanation stay consistent, and averaging adds no measurable gain | Single-model verdict |
| Rules are three-valued: fired / not fired / unknown | A rule must never fire on a guessed (imputed) `thal`/`slope`/`ca` | Rule verdict is often "undetermined" ({1 - ru['coverage_determinate']:.0%} of test patients) |
| Advisor = Task 3 A* over tests needed to make the rule verdict decisive, plus ML sensitivity ranking | Reuses Task 3; the ranking shows whether a test could actually flip the verdict | Costs from context.md, not clinical pricing |
| SHAP via XGBoost native `pred_contribs` | Exact TreeSHAP, no extra dependency | XGBoost only |
| DNN in numpy at inference (PyTorch used only to train) | No heavy runtime dependency; TensorFlow would not load on the dev machine | Weights exported to JSON |
| Imputer, scaler and models fit on the train split only | No leakage into val/test | Slightly less data per fit |

## 3. Models (Tasks 6-7)
XGBoost chosen by 5-fold CV AUC on the training split from a small grid (selected: {json.dumps(meta['xgb_params'])}). DNN: Dense 64-32-16 with BatchNorm and Dropout, Adam 1e-3, early stopping on val loss,
stopped at epoch {meta['dnn_epochs']}.

{table(cmp_rows, ["model", "CV AUC", "test acc", "test F1", "test AUC"])}

## 4. Testing report
{t}. Covers: feature parity vs `Task5_Feature_Matrix.csv` (max diff < 1e-9), hand-checked formulas, numpy-DNN vs trained-DNN AUC parity, rule tri-state and boundaries, field-level validation errors,
all four demo patients end to end, determinism, A* plan, cleaning steps, and a dashboard smoke test for every demo patient.
Robustness (`evaluate.py`): invalid inputs rejected {rob['invalid_inputs_rejected']}; random valid inputs processed without error {rob['fuzz_valid_inputs_ok']}.
Latency, full pipeline including SHAP, counterfactual and advisor: p50 {lat['p50']:.0f} ms, p95 {lat['p95']:.0f} ms (target < 500 ms).

## 5. Evaluation report (held-out test, n = {ev['models']['xgb']['n']})
{table(mods, ["model", "accuracy", "precision", "recall", "roc_auc", "brier"])}

AUC 95% bootstrap CI: XGBoost {f(ev['models']['xgb']['auc_ci95'][0], 2)}-{f(ev['models']['xgb']['auc_ci95'][1], 2)}, DNN {f(ev['models']['dnn']['auc_ci95'][0], 2)}-{f(ev['models']['dnn']['auc_ci95'][1], 2)}.
The intervals overlap, so model differences are not statistically meaningful at this sample size. Brier baseline (always predict prevalence): {f(cal['brier_baseline_prevalence'])}.

**Rule base vs ML.** The rules are decisive for {ru['coverage_determinate']:.0%} of patients. On those: rule accuracy {f(ru['rule_accuracy_on_determinate'])}, ML accuracy {f(ru['ml_accuracy_on_determinate'])}.
They agree {ru['agreement_rate']:.0%} of the time; ML accuracy is {f(ru['ml_accuracy_when_agree'])} when they agree and {f(ru['ml_accuracy_when_disagree'])} when they disagree (n = {ru['n_disagree']}).
Disagreement is therefore a useful warning signal.

**XGBoost vs DNN.** They disagree on {md_['rate']:.0%} of patients; XGBoost accuracy is {f(md_['xgb_acc_when_agree'])} when they agree and {f(md_['xgb_acc_when_disagree'])} when they disagree.

**Trust.** Accuracy by confidence band (test):

{table(bands, ["confidence", "n", "accuracy"])}

Conformal prediction set at {cf['target']:.0%}: empirical coverage {cf['empirical_coverage']:.1%}; single-label sets {cf['frac_single']:.0%}, both-label ("uncertain") {cf['frac_both']:.0%}. Reliability plot: `reports/figures/calibration.png`.

**Missing optional fields (ablation).**

{table(abl, ["subset", "n", "accuracy", "AUC"])}

Small groups, so treat as indicative. Hiding `slope`/`ca`/`thal` from every test patient changes AUC only slightly, so the models lean mostly on symptoms and risk factors rather than these tests.
The reliability warning is kept because the imputed value can still be wrong for an individual.

**Global feature importance (mean |SHAP|)**

{table(shap, ["feature", "mean |SHAP|"])}

## 6. Responsible AI report
| Area | Finding / mitigation |
|---|---|
| Intended use | Educational decision support, one patient at a time. Disclaimer on every screen and report. Not a diagnostic device. |
| Data | Public research data from four hospitals, collected decades ago; not representative of any current population. |
| Missing data | Optional fields are flagged, never silent; 2+ imputed fields block a "high" confidence band; rules are not evaluated on imputed values. |
| Out-of-distribution | Age outside the training range triggers a warning. |
| Transparency | SHAP per patient, plain-language summary, rule trace, model agreement chips. The DNN has no per-patient explanation, stated in the UI. |
| Calibration and uncertainty | Trust bands from validation accuracy, conformal set, XGB-vs-DNN and ML-vs-rule disagreement flags. |
| Counterfactuals | Reported as model sensitivity. "Actionable" covers only modifiable inputs (cholesterol, blood pressure, fasting glucose flag); test results are never presented as changeable. |
| Privacy | Stateless; no patient data stored or logged. |
| Reproducibility | Fixed seeds, pinned split, saved artifacts, determinism test. |

Fairness (test set; groups are small, so differences are weak evidence):

{table(fair, ["group", "n", "AUC", "recall", "precision", "prevalence"])}

Limits to state plainly: female patients are a small share of the data; site prevalence differs a lot (so site is a confounder the model cannot see); the test set is small; no external validation.

## 7. User manual
1. `streamlit run app.py` and open the page. The "Health check" view is for users; "How it works" is for reviewers.
2. Describe symptoms in your own words (optional) or just press Start. Answer the five short steps; hover the "?" next to any field for a plain explanation.
   Typical values are pre-filled on the numbers page: replace them with real ones.
3. Read the overview: risk pattern and estimated chance, how sure the model is, information completeness, and any "things to keep in mind".
4. Tabs: Why this result (domain impacts, top influences, three independent opinions), Your measurements (each answer against reference ranges, with explanations),
   What-if (how the estimate moves with cholesterol, blood pressure or peak heart rate), Next steps (what to do, ranked tests, doctor questions, report download).
5. Ask SymbioForge: use the suggested questions or type your own ("What does thallium mean?").
6. Quick demo: use the four ready-made examples on the first screen (higher risk, lower risk, borderline with missing tests, rules vs model disagree).
7. Safety: the page always shows an emergency notice; this is not a diagnosis.

## 8. Deployment guide
Local: `pip install -r requirements.txt && streamlit run app.py`. Cloud: push the repo to GitHub, open Streamlit Community Cloud, new app, main file `app.py`,
Python 3.11+. No secrets, no database. Retrain: `pip install -r requirements-train.txt && python train.py && python evaluate.py && python build_docs.py`.
Artifacts are small (under 300 KB) and committed. XGBoost is stored as native JSON, so it does not depend on the pickle/version of the training machine.

## 9. Limitations and future work
Not clinically validated; small test set; single split (cross-validation was used only for model selection); no external or temporal validation; DNN not explainable per patient;
cost table is a proxy. Future: repeated-CV evaluation, site-held-out validation, calibrated probabilities (isotonic), clinician usability study, EDA/correlation report for Task 4-5 deliverables.
"""
(R / "docs/PROJECT_REPORT.md").write_text(doc, encoding="utf-8")
