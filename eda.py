"""Task 4-5 EDA + correlation report. Run: python eda.py -> reports/EDA_report.md, reports/figures/eda_*.png"""
from __future__ import annotations

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from cdss import DATA, REPORTS
from cdss.features import FEATURES, NUMERIC, clean_raw

FIG = REPORTS / "figures"
FIG.mkdir(parents=True, exist_ok=True)
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})
BLUE, RED = "#2b6cb0", "#c53030"

raw = pd.read_csv(DATA / "heart_dataset.csv")
rawq = raw.replace("?", np.nan)
clean = clean_raw(raw)                                  # NaNs preserved (before imputation)
full = pd.read_csv(DATA / "Task4_clean_dataset.csv")    # imputed
feat = pd.read_csv(DATA / "Task5_Feature_Matrix.csv")
md = lambda df, idx=True: df.to_markdown(index=idx) if hasattr(df, "to_markdown") else "```\n" + df.to_string(index=idx) + "\n```"

try:
    import tabulate  # noqa: F401
except ImportError:
    def md(df, idx=True):
        d = df.reset_index() if idx else df
        cols = list(d.columns)
        rows = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
        rows += ["| " + " | ".join(f"{v:.3f}" if isinstance(v, float) else str(v) for v in r) + " |" for r in d.itertuples(index=False)]
        return "\n".join(rows)

out = ["# EDA and Data Quality Report (Tasks 4-5)", "",
       "Generated by `eda.py`. Raw file `data/heart_dataset.csv`; cleaned per context.md section 5.", ""]

# ---- 1. data quality ----
dq = pd.DataFrame({
    "missing '?' / NaN": rawq.isna().sum(),
    "disguised zeros": [(raw[c] == 0).sum() if c in ("chol", "trestbps") else 0 for c in raw.columns],
})
dq["% missing after zero->NaN"] = ((dq["missing '?' / NaN"] + dq["disguised zeros"]) / len(raw) * 100).round(1)
dq = dq[dq.iloc[:, :2].sum(axis=1) > 0]
dup = len(raw.drop(columns=["id"]).drop_duplicates())
out += ["## 1. Data quality", f"- Rows: {len(raw)} raw -> {len(clean)} after dropping {len(raw) - dup} exact duplicate row(s) (id ignored).",
        f"- Columns: {raw.shape[1]} raw; target `num` (0-4) binarised to `target` (present if num > 0); prevalence {clean.target.mean():.1%}.",
        "- `chol == 0` and `trestbps == 0` are disguised missing values, converted to NaN before imputation.", "",
        md(dq), ""]

# missingness by site
miss_site = clean.groupby("dataset")[["trestbps", "chol", "thalch", "oldpeak", "fbs", "exang", "slope", "ca", "thal"]].apply(lambda g: g.isna().mean() * 100).round(0)
prev_site = clean.groupby("dataset").agg(n=("target", "size"), prevalence=("target", "mean"))
out += ["### Missingness (%) by site", md(miss_site), "",
        "### Sample size and disease prevalence by site", md(prev_site), "",
        "**Finding.** Missingness and prevalence both depend heavily on the site (e.g. Switzerland has almost no observed `chol` and the highest prevalence). "
        "Any value used to fill gaps must therefore not be a single constant, or the model can learn the site as a proxy for disease (see ARCHITECTURE D7).", ""]
fig, ax = plt.subplots(figsize=(7, 3.2))
im = ax.imshow(miss_site.values, cmap="Reds", vmin=0, vmax=100, aspect="auto")
ax.set_xticks(range(miss_site.shape[1])); ax.set_xticklabels(miss_site.columns, rotation=45, ha="right")
ax.set_yticks(range(miss_site.shape[0])); ax.set_yticklabels(miss_site.index)
for (i, j), v in np.ndenumerate(miss_site.values):
    ax.text(j, i, int(v), ha="center", va="center", fontsize=8, color="white" if v > 55 else "black")
ax.set_title("% missing by site"); fig.colorbar(im, ax=ax, fraction=0.03)
fig.tight_layout(); fig.savefig(FIG / "eda_missing_by_site.png", dpi=150); plt.close(fig)

# ---- 2. statistical summary ----
num_cols = ["age", "trestbps", "chol", "thalch", "oldpeak"]
summ = clean[num_cols].describe().T[["count", "mean", "std", "min", "25%", "50%", "75%", "max"]].round(2)
summ["skew"] = clean[num_cols].skew().round(2)
out += ["## 2. Statistical summary (observed values only)", md(summ), ""]
cat_rows = []
for c in ("sex", "cp", "restecg", "slope", "thal", "fbs", "exang", "ca"):
    vc = clean[c].value_counts(dropna=False)
    cat_rows.append({"column": c, "levels": "; ".join(f"{k}: {v}" for k, v in vc.items())})
out += ["### Categorical counts", md(pd.DataFrame(cat_rows), idx=False), ""]

# ---- 3. outliers (IQR, retained) ----
rows = []
for c in num_cols:
    s = clean[c].dropna()
    q1, q3 = s.quantile([.25, .75])
    lo, hi = q1 - 1.5 * (q3 - q1), q3 + 1.5 * (q3 - q1)
    rows.append({"column": c, "lower fence": round(lo, 1), "upper fence": round(hi, 1), "outliers": int(((s < lo) | (s > hi)).sum())})
out += ["## 3. Outliers (IQR rule)", md(pd.DataFrame(rows), idx=False),
        "", "Policy (context.md section 5 step 7): outliers are **retained**; they are clinically plausible extremes, not entry errors.", ""]

# ---- 4. distributions by target ----
fig, axs = plt.subplots(2, 3, figsize=(9, 5))
for ax, c in zip(axs.ravel(), num_cols):
    for t, col, lab in ((0, BLUE, "absent"), (1, RED, "present")):
        ax.hist(clean.loc[clean.target == t, c].dropna(), bins=20, alpha=.6, color=col, label=lab)
    ax.set_title(c)
axs.ravel()[0].legend(frameon=False)
tgt = clean.target.value_counts().sort_index()
axs[1, 2].bar(["absent", "present"], tgt.values, color=[BLUE, RED]); axs[1, 2].set_title("target balance")
fig.tight_layout(); fig.savefig(FIG / "eda_distributions.png", dpi=150); plt.close(fig)

cats = ("cp", "sex", "slope", "thal", "restecg", "exang")
fig, axs = plt.subplots(2, 3, figsize=(10, 5))
rate_rows = []
for ax, c in zip(axs.ravel(), cats):
    g = clean.groupby(c, dropna=True)["target"].agg(["mean", "size"]).sort_values("mean")
    ax.barh([str(i) for i in g.index], g["mean"], color=BLUE)
    for i, (m_, n_) in enumerate(zip(g["mean"], g["size"])):
        ax.text(m_ + .01, i, f"n={n_}", va="center", fontsize=7)
    ax.set_xlim(0, 1.15); ax.set_title(f"P(disease) by {c}")
    rate_rows += [{"variable": c, "level": str(i), "n": int(r["size"]), "P(disease)": round(r["mean"], 3)} for i, r in g.iterrows()]
fig.tight_layout(); fig.savefig(FIG / "eda_target_by_category.png", dpi=150); plt.close(fig)
out += ["## 4. Distributions and target relationships",
        "![distributions](figures/eda_distributions.png)", "![target by category](figures/eda_target_by_category.png)", "",
        "**Findings.** Asymptomatic chest pain is by far the strongest single marker of disease (consistent with Tasks 1, 2 and 8). "
        "Males, flat/downsloping ST slope, exercise angina and abnormal `thal` all show higher disease rates. The classes are roughly balanced, so accuracy is a usable headline metric.", ""]

# ---- 5. correlation ----
f = feat[FEATURES + ["target"]]
corr = f.corr()
fig, ax = plt.subplots(figsize=(7, 6))
im = ax.imshow(corr.values, cmap="RdBu_r", vmin=-1, vmax=1)
ax.set_xticks(range(len(corr))); ax.set_xticklabels(corr.columns, rotation=60, ha="right", fontsize=7)
ax.set_yticks(range(len(corr))); ax.set_yticklabels(corr.columns, fontsize=7)
for (i, j), v in np.ndenumerate(corr.values):
    ax.text(j, i, f"{v:.1f}", ha="center", va="center", fontsize=6, color="white" if abs(v) > .6 else "black")
ax.set_title("Correlation: 12 selected features + target"); fig.colorbar(im, ax=ax, fraction=0.04)
fig.tight_layout(); fig.savefig(FIG / "eda_correlation.png", dpi=150); plt.close(fig)
tc = corr["target"].drop("target").sort_values(key=abs, ascending=False).round(3)
pairs = [(a, b, corr.loc[a, b]) for i, a in enumerate(FEATURES) for b in FEATURES[i + 1:] if abs(corr.loc[a, b]) >= 0.7]
mi = pd.read_csv(REPORTS / "feature_mutual_info.csv", index_col=0)["mutual_info"].round(3)
out += ["## 5. Correlation and feature importance (Task 5)", "![correlation](figures/eda_correlation.png)", "",
        "### Correlation with target", md(tc.to_frame("pearson r")), "",
        "### Highly correlated feature pairs (|r| >= 0.7)",
        md(pd.DataFrame(pairs, columns=["feature A", "feature B", "r"]).round(3), idx=False) if pairs else "None.", "",
        "### Mutual information with target (train split)", md(mi.to_frame("mutual information")), "",
        "**Findings.** Derived features (`hr_reserve`, `rate_pressure_product`, `oldpeak_slope_risk`) are strongly related to their parents "
        "(`thalch`, `age`, `oldpeak`), so there is redundancy; tree models and the regularised DNN tolerate this, but linear coefficients "
        "should not be interpreted individually. Final model uses the 12 features fixed in context.md section 6.", ""]

# ---- 6. site effect check ----
by = clean.groupby("dataset").target.mean().round(2).to_dict()
out += ["## 6. Caveats", f"- Disease prevalence by site: {by}. Site is not a model input, but it confounds every column that is missing selectively.",
        "- Female patients are a minority; subgroup results have wide uncertainty (see evaluation fairness table).",
        "- Data are historical research data, not representative of current clinical populations.", ""]

(REPORTS / "EDA_report.md").write_text("\n".join(out), encoding="utf-8")
print("EDA written:", len("\n".join(out)), "chars;", len(list(FIG.glob("eda_*.png"))), "figures")
